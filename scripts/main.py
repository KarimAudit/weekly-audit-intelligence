def _extract_json(text: str) -> Optional[dict]:
    if not text:
        return None
    cleaned = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip(), flags=re.MULTILINE)
    match = re.search(r"\{.*\}", cleaned, flags=re.DOTALL)
    candidate = match.group(0) if match else cleaned
    try:
        return json.loads(candidate)
    except json.JSONDecodeError as e:
        log.error(f"JSON parse failure: {e}")
        return None


def _validate_content_shape(data: dict) -> bool:
    """
    تحقق دفاعي: تأكد إن المفاتيح "الآنية" (التي يُفترض أن ينتجها الـ LLM)
    موجودة، حتى لو القيم فاضية، بدل ما ينهار السكربت لاحقًا بـ KeyError غامض.
    الأركان الدائمة (flashback, book_of_week, ...) تُحقَن دومًا كودًا في
    generate_newsletter_content ولا تحتاج تحققًا هنا لأنها مضمونة الوجود.
    """
    required_keys = ["issue_theme", "editor_note", "exec_brief", "domain_updates", "further_reading"]
    missing = [k for k in required_keys if k not in data]
    if missing:
        log.error(f"استجابة LLM ناقصة المفاتيح التالية: {missing}")
        return False
    if not isinstance(data.get("domain_updates"), list) or not data["domain_updates"]:
        log.error("حقل domain_updates فاضي أو ليس قائمة — لا فائدة من نشرة بدون تحديثات.")
        return False
    return True


def generate_newsletter_content() -> Tuple[Optional[Dict[str, Any]], bool]:
    """يبني المحتوى بالكامل: بحث Tavily، توليد LLM للقسم الآني، ثم حقن
    الأركان التحريرية الدائمة من المكتبات الدوّارة (بلا أي تدخل من الـ LLM)."""

    # 1. البحث الفعلي
    search_context = search_with_tavily(DOMAINS)
    if not search_context:
        log.error("Pipeline STOPPED: تعذر جلب نتائج البحث من Tavily.")
        return None, False

    # 2. توليد الجزء "الآني" فقط عبر الـ LLM
    prompt = build_generation_prompt(search_context)
    raw_response = generate_with_llm(prompt)
    if not raw_response:
        return None, False

    data = _extract_json(raw_response)
    if not data:
        log.error("FATAL: تعذر تحليل استجابة الـ LLM كـ JSON.")
        log.error(f"Raw LLM response (first 2000 chars): {raw_response[:2000]}")
        return None, False

    # قيم افتراضية آمنة للحقول الآنية الاختيارية (قد تكون فارغة شرعًا هذا
    # الأسبوع، لكن يجب أن تكون موجودة كمفتاح لتفادي KeyError لاحقًا)
    data.setdefault("stat_of_week", {})
    data.setdefault("standards_watch", [])
    data.setdefault("exec_brief", [])
    data.setdefault("further_reading", [])

    # 3. حقن الأركان التحريرية الدائمة — بلا أي علاقة بالـ LLM أو نتائج البحث
    week = get_week_number()
    data["flashback"] = pick_flashback(week)
    data["book_of_week"] = pick_book_of_week(week)
    data["growth_corner"] = pick_growth_corner(week)
    data["wellbeing_corner"] = pick_wellbeing_tip(week)
    data["pro_skills"] = pick_pro_skills(week)
    data["term_of_week"] = pick_term_of_week(week)

    if not _validate_content_shape(data):
        log.error(
            f"Raw LLM response length: {len(raw_response)} chars. "
            f"Last 500 chars (لمعرفة هل الرد اتقطع في النهاية): ...{raw_response[-500:]}"
        )
        return None, False

    log.info(
        f"Content generated successfully: {len(data.get('domain_updates', []))} domain updates, "
        f"{len(data.get('standards_watch', []))} standards-watch items, "
        f"stat_of_week={'present' if data.get('stat_of_week') else 'empty'}."
    )
    return data, True

