def pick_pro_skills(week: int) -> Dict[str, Any]:
    """يختار فئة مهارات واحدة أسبوعيًا (تدور كل 4 أسابيع)، ومجموعة من 3
    نصائح ضمنها (تدور كل جولتين عبر الفئة نفسها لتفادي التكرار السريع)."""
    categories = list(PRO_SKILLS_POOL.keys())
    cat = categories[week % len(categories)]
    tips = PRO_SKILLS_POOL[cat]
    rounds = max(1, len(tips) // 3)
    cycle = (week // len(categories)) % rounds
    start = (cycle * 3) % len(tips)
    selected = tips[start:start + 3]
    if len(selected) < 3:
        selected = (tips + tips)[start:start + 3]
    return {"category": cat, "tips": selected}


