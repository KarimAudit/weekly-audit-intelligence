"""
النشرة الأسبوعية للحوكمة والتدقيق الداخلي — Governance & Audit Weekly
=======================================================================
هذا الإصدار يطوّر المحتوى (لا الشكل) ليضاهي نشرات INTOSAI وماكنزي والبيغ فور.

الفلسفة المعمارية الجديدة (لماذا تغيّر الكود بهذا الشكل)
----------------------------------------------------------
الإصدار السابق كان يطلب من نموذج LLM واحد (وغالبًا نموذج سريع/اقتصادي مثل
glm-4-flash) توليد *كل* محتوى النشرة من الصفر أسبوعيًا: الأخبار، الومضة
الإدارية، كتاب الأسبوع، الانتصارات السريعة... إلخ. هذا هو السبب الجذري لضعف
الإنتاج: الأقسام "الدائمة" (مفاهيم إدارية كلاسيكية، توصيات كتب، عادات مهنية،
نصائح صحة مهنية) لا تحتاج فعليًا إلى توليد حر أسبوعي، ونموذج سريع/رخيص يميل
فيها إلى الحشو والعمومية لأنه لا يوجد سياق بحث حقيقي يقيّده.

لذلك تم فصل النشرة إلى نصفين:

  1) محتوى "آني" يعتمد على البحث الفعلي (Tavily) ويُنتَج عبر LLM أسبوعيًا:
     عنوان العدد، كلمة التحرير، نظرة سريعة تنفيذية، رقم الأسبوع، رادار
     المعايير والإصدارات الجديدة، أبرز التطورات حسب المجال، وللقراءة هذا
     الأسبوع. هذا هو العمل الذي يحتاج فعلاً إلى ذكاء اصطناعي وبحث حي.

  2) محتوى "دائم" تحريري مُعَدّ ومُراجَع مسبقًا (بواسطتنا، لا بواسطة الـ LLM
     الأسبوعي)، يُسحَب من مكتبات دوّارة مخزَّنة في هذا الملف نفسه: الومضة
     الإدارية، كتاب الأسبوع، مسار الاحتراف، لحظة توازن، مهارات الأسبوع،
     ومصطلح الأسبوع. هذا يضمن جودة ثابتة عالية كل أسبوع بلا اعتماد على مزاج
     نموذج صغير، ويحرّر الـ LLM ليركّز فقط على ما يحتاج فعلاً إلى بحث آني.

     ملاحظة تحريرية: هذه المكتبات (FLASHBACK_POOL, BOOK_POOL, ...) هي بيانات
     عادية في الكود، يمكن لأي محرر بشري توسيعها أو تعديلها بسهولة لاحقًا دون
     المساس بمنطق البرنامج — هذا بالتصميم، فالتحكم التحريري ميزة لا قيدًا.

Pipeline:
  1) Tavily API للبحث عن آخر التطورات في المجالات الثمانية، ومصادر منفصلة
     مخصصة لـ further_reading و standards_watch.
  2) نموذج LLM (GLM-4-Flash / DeepSeek) لتوليد JSON منظم للمحتوى الآني فقط.
  3) حقن المحتوى الدائم (الومضة، الكتاب، مسار الاحتراف، توازن، المهارات،
     المصطلح) من المكتبات الدوّارة أدناه.
  4) بناء ملف Word فاخر التصميم من الـ JSON المدمج.
  5) تحويل DOCX -> PDF.
  6) بناء إيميل HTML مطابق وإرساله.

المتغيرات البيئية المطلوبة:
  TAVILY_API_KEY
  LLM_PROVIDER (glm | deepseek | openai)
  LLM_API_KEY
  LLM_MODEL (e.g., glm-4-flash)
  SENDER_EMAIL, SENDER_PASSWORD, RECIPIENT_EMAILS

اختياري:
  SMTP_SERVER, SMTP_PORT    افتراضي smtp.gmail.com / 465
  LLM_MAX_TOKENS            افتراضي 14000 (انظر التعليق عند التعريف لسبب الرفع)

الحزم المطلوبة (requirements.txt): requests, python-docx,
python-dotenv (اختياري), docx2pdf (اختياري).

خطوط عربية على CI: يجب تثبيت fonts-hosny-amiri و fonts-crosextra-carlito
قبل تشغيل هذا السكربت.
"""

